export function getBiomeForDepth(depth: number, seed = 482913): BiomeConfig {
  const safeDepth = Math.max(1, depth);
  const biomeId: BiomeId =
    safeDepth <= 10
      ? 'SUNKEN_MASONRY'
      : safeDepth <= 20
      ? 'ASHEN_FOUNDRY'
      : 'VITRIOL_VAULTS';
  return generateBiomePalette(biomeId, safeDepth, seed);
}

